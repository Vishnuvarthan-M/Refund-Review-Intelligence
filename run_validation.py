from pathlib import Path

import pandas as pd

from src.ai_review import review_refund_frame
from src.pipeline import clean_and_reconcile, load_data
from src.validation import score_reference_validation, select_validation_sample


ROOT = Path(__file__).resolve().parent
SAMPLE_SIZE = 30
RANDOM_STATE = 20261005


def markdown_table(frame: pd.DataFrame) -> str:
    headers = [str(column) for column in frame.columns]
    rows = [[str(value).replace("|", "\\|").replace("\n", " ") for value in row] for row in frame.itertuples(index=False, name=None)]
    lines = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    lines.extend("| " + " | ".join(row) + " |" for row in rows)
    return "\n".join(lines)


def build_validation_report() -> tuple[str, pd.DataFrame]:
    tickets, agents, orders, products, customers = load_data(str(ROOT))
    cleaned, _ = clean_and_reconcile(tickets, agents, orders, products, customers)
    sample = select_validation_sample(cleaned, SAMPLE_SIZE, RANDOM_STATE)
    predictions = review_refund_frame(sample.assign(is_refund=True))
    labels = pd.read_csv(ROOT / "validation_labels.csv")
    if set(labels["ticket_id"]) != set(sample["ticket_id"]):
        raise ValueError("validation_labels.csv must label exactly the reproducible sample")
    results = labels.merge(
        predictions[["ticket_id", "assessment", "likely_reason", "confidence", "evidence_summary"]],
        on="ticket_id",
        how="inner",
        validate="one_to_one",
    )
    results["correct"] = results["reference_assessment"].eq(results["assessment"])
    summary = score_reference_validation(labels, predictions[["ticket_id", "assessment"]])
    errors = results.loc[~results["correct"]]
    error_counts = errors["error_category"].value_counts().rename_axis("Error category").reset_index(name="Count")
    if error_counts.empty:
        error_counts = pd.DataFrame(columns=["Error category", "Count"])
    error_table = errors[["ticket_id", "reference_assessment", "assessment", "error_category"]].rename(
        columns={"ticket_id": "Ticket", "reference_assessment": "Provisional reference", "assessment": "Rule output", "error_category": "Error category"}
    )
    report = f"""# Text Review Validation

Generated by `python run_validation.py` from the supplied ticket CSV and `validation_labels.csv`.

## Method

- Sample: {summary['sample_size']} refund tickets, selected without replacement using pandas sampling with fixed seed `{RANDOM_STATE}`.
- Sampling frame: all canonical records with a recorded refund; selection is uniform, not stratified.
- Reference labels: GitHub Copilot assigned provisional labels while inspecting each customer message and agent note. These are not labels from an independent human reviewer.
- Automated system: local deterministic evidence rules, not a generative model. Gemini was not used for these results.
- The same fixed sample was consulted while improving keyword rules. The comparison is self-agreement on a calibration sample, not human validation and not out-of-sample accuracy.
- Scoring: exact agreement across `supported`, `probably_supported`, `unsupported`, and `ambiguous`.

## Results

| Measure | Result |
|---|---:|
| Sample size | {summary['sample_size']} |
| Exact provisional-label agreement | {summary['correct']} / {summary['sample_size']} |
| Disagreements | {summary['incorrect']} |
| Apparent agreement rate (not accuracy) | {summary['accuracy']:.1%} |
| Human-validated error rate | Not measured |

## Error Categories

{markdown_table(error_counts) if not error_counts.empty else "No errors in this run."}

## Disagreements

{markdown_table(error_table) if not error_table.empty else "No disagreements."}

The observed 30/30 exact agreement is self-agreement against provisional labels created by the same assistant during rule refinement. It must not be described as model accuracy. Human accuracy/error rate is unknown. Before deployment, freeze the reviewer and ask an independent human reviewer (preferably two) to adjudicate a fresh untouched sample. Ambiguous or conflicting cases should remain in human review. Provisional labels and exact outcomes are exported to `validation-results.csv`.
"""
    return report, results


def main() -> None:
    report, results = build_validation_report()
    (ROOT / "VALIDATION_REPORT.md").write_text(report, encoding="utf-8")
    results.to_csv(ROOT / "validation-results.csv", index=False)
    print("Wrote VALIDATION_REPORT.md and validation-results.csv")


if __name__ == "__main__":
    main()
